def _fuse(local, detector=None):
    # Local signal heuristics remain weak evidence. A real detector model gets
    # more weight, but the final score is still pulled toward uncertainty.
    score = 50.0 * 0.35 + local * 0.65
    if detector is not None:
        score = score * 0.35 + detector * 0.65
    return _clamp(score)

def _finish(result):
    score = result.ai_likelihood
    distance = abs(score - 50)
    if result.remote_used and distance >= 25 and len(result.evidence) >= 2:
        result.confidence = "high"
    elif distance >= 18 and len(result.evidence) >= 2:
        result.confidence = "medium"
    else:
        result.confidence = "low"
    if score >= 75:
        result.decision = "likely_ai"
    elif score <= 25:
        result.decision = "likely_human"
    else:
        result.decision = "uncertain"
    result.ai_likelihood = round(_clamp(score), 1)
    return result

async def analyze_image_bytes(data, filename="image"):
    started = time.perf_counter()
    if not data or len(data) > MAX_BYTES:
        raise DetectorError(
            "image exceeds the %d MB detector limit" % (MAX_BYTES // (1024 * 1024))
        )
    try:
        with Image.open(io.BytesIO(data)) as im:
            im.verify()
    except Exception as exc:
        raise DetectorError("unsupported or corrupted image") from exc

    result = DetectionResult("image")
    result.stages.append("metadata")
    meta, strong = await asyncio.to_thread(inspect_metadata, data, filename)
    result.evidence.extend(meta)
    if strong:
        result.ai_likelihood = 98.0
        result.stages.append("metadata_decisive")
        result.warnings.append(
            "A generator/provenance signature was found; signatures can be stripped or forged."
        )
        result.elapsed_ms = int((time.perf_counter() - started) * 1000)
        result.confidence = "high"
        result.decision = "likely_ai"
        return result

    result.stages.append("local_heuristics")
    local, ev = await asyncio.to_thread(image_heuristics, data)
    result.evidence.extend(ev)
    result.ai_likelihood = _fuse(local)

    if LOW < result.ai_likelihood < HIGH:
        result.stages.append("local_onnx")
        onnx_score = await asyncio.to_thread(local_onnx_image, data)
        if onnx_score is not None:
            result.ai_likelihood = _fuse(local, onnx_score)
            result.evidence.append(Evidence(
                "onnx",
                "Local CPU ONNX detector score: %.1f%% AI-like." % onnx_score,
                40,
                onnx_score,
            ))
        if LOW < result.ai_likelihood < HIGH:
            result.stages.append("free_hf_inference")
            remote = await remote_image(data)
            if remote:
                result.ai_likelihood = _fuse(local, remote[0])
                result.evidence.append(Evidence("remote", remote[1], 55, remote[0]))
                result.remote_used = True
            else:
                result.warnings.append(
                    "Free external inference was unavailable or rate-limited; local evidence only."
                )
    result.warnings.append("No AI signature does not prove human origin.")
    result.elapsed_ms = int((time.perf_counter() - started) * 1000)
    return _finish(result)

