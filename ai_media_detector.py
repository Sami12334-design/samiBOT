def format_detection_result(result):
    icon = {
        "likely_ai": "🤖",
        "likely_human": "🧑",
        "uncertain": "❓",
    }[result.decision]
    lines = [
        "%s <b>AI Media Check</b>" % icon,
        "AI likelihood: <b>%.0f%%</b>" % result.ai_likelihood,
        "Confidence: <b>%s</b>" % result.confidence,
        "Result: <b>%s</b>" % result.decision.replace("_", " "),
        "",
        "<b>Evidence</b>",
    ]
    for item in result.evidence[:6]:
        lines.append("• " + item.message)
    if result.warnings:
        lines.append("")
        lines.append("<b>Important</b>")
        for warning in result.warnings[:3]:
            lines.append("• " + warning)
    lines.append(
        "\n⏱ %d ms • %s" % (result.elapsed_ms, " → ".join(result.stages))
    )
    return "\n".join(lines)
